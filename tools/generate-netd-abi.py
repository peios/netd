#!/usr/bin/env python3
"""Generate matching C and Rust layouts from the reviewed ABI declaration list."""

import argparse
import json
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRIMITIVES = {
    "u8": "uint8_t",
    "u32": "uint32_t",
    "u64": "uint64_t",
    "i16": "int16_t",
    "i32": "int32_t",
    "i64": "int64_t",
    "usize": "size_t",
}


def c_name(name: str) -> str:
    """Translate a Rust layout name into its stable public C name."""
    return "peios_netd_" + re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def c_type(name: str) -> str:
    """Translate a schema type, retaining pointer constness."""
    if name.startswith("*const "):
        return "const " + c_type(name[7:]) + " *"
    return PRIMITIVES.get(name, c_name(name))


def main() -> None:
    """Regenerate layouts in schema order without changing the ABI."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Verify outputs without modifying them"
    )
    args = parser.parse_args()
    declarations = json.loads((ROOT / "tools/netd-abi.json").read_text())
    rust = [
        "//! Shared C layouts. Use netd-client for safe, owned Rust interfaces.",
        "//! Generated by tools/generate-netd-abi.py; see netd.h for field contracts.",
    ]
    header = [
        "/* Generated by tools/generate-netd-abi.py; see netd.h for field contracts. */",
        "#ifndef PEIOS_NETD_TYPES_H",
        "#define PEIOS_NETD_TYPES_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
    ]
    header.append("typedef struct peios_netd_key peios_netd_key;")
    for name, fields in declarations.items():
        rust.extend(["#[repr(C)]", "#[derive(Clone, Copy)]", f"pub struct {name} {{"])
        rust.extend(f"    pub {field}: {kind}," for field, kind in fields)
        rust.append("}")
        header.append("typedef struct " + c_name(name) + " {")
        header.extend(
            "    " + c_type(kind) + ("" if c_type(kind).endswith("*") else " ") + field + ";"
            for field, kind in fields
        )
        header.append("} " + c_name(name) + ";")
    header.append("#endif")
    outputs = {
        "netd-abi/src/lib.rs": "\n".join(rust) + "\n",
        "libnetd/include/peios/netd-types.h": "\n".join(header) + "\n",
    }
    with tempfile.TemporaryDirectory(prefix="netd-abi-") as temporary:
        for name, content in outputs.items():
            generated = Path(temporary) / Path(name).name
            generated.write_text(content)
            if generated.suffix == ".rs":
                command = [
                    "rustup",
                    "run",
                    "1.98.1",
                    "rustfmt",
                    "--config-path",
                    str(ROOT / "tools/rustfmt.toml"),
                ]
            else:
                command = [
                    "clang-format",
                    "--style=file:" + str(ROOT / "tools/clang-format.yaml"),
                    "-i",
                ]
            subprocess.run([*command, str(generated)], check=True)
            destination = ROOT / name
            if args.check:
                if destination.read_bytes() != generated.read_bytes():
                    raise SystemExit(f"{name} is stale; run tools/generate-netd-abi.py")
            else:
                destination.write_bytes(generated.read_bytes())


if __name__ == "__main__":
    main()
